WITH SalesData AS (
    SELECT
        a.sid,
        a.invc_post_date,
        a.post_date,
        a.store_code,
        a.doc_no,
        a.DISC_PERC AS Bill_Disc_Perc,
        a.tender_name,
        a.RECEIPT_TYPE,
        a.BT_PRIMARY_PHONE_NO,
        a.BT_EMAIL,
        a.MODIFIED_Datetime,
        a.modified_by,
        a.notes_lostdoc,
        b.invn_sbs_item_sid,
        b.item_type,
        b.qty,
        b.orig_price,
        b.DISC_PERC AS Item_Disc_Perc,
        b.Price,
        b.vend_code,
        b.employee1_SID,
        b.EMPLOYEE1_LOGIN_NAME,
        b.dcs_code,
        c.FIRST_NAME AS Customer_Name,
        c.info1 AS Cust_Type,
        c.UDF1_STRING AS Valid_From,
        c.udf1_date AS Cust_Birthday,
        c.FIRST_SALE_DATE AS First_Sale,
        c.LAST_SALE_DATE AS Last_Sale,
        c.CUST_ID,
        i.upc,
        i.alu,
        i.description1,
        i.description2,
        i.TEXT1,
        i.attribute,
        i.item_size,
        i.COST AS Landed_Cost,
        i.UDF1_STRING AS Base_Cost,
        i.UDF5_STRING AS Season,
        v.vend_name,
        a.CASHIER_LOGIN_NAME
    FROM rps.document a
    JOIN rps.document_item b ON a.sid = b.doc_sid
    
    JOIN rps.invn_sbs_item i ON i.sid = b.invn_sbs_item_sid
    left JOIN RPS.CUSTOMER c ON c.SID = a.BT_CUID
    left JOIN rps.VENDOR v ON b.vend_code = v.vend_code
    WHERE a.receipt_type IN (0, 1) AND b.item_type IN (1, 2) AND a.status = 4 --and doc_no = 141 and store_code = 'RWP'
),
CalculatedData AS (
    SELECT
        sid,
        invc_post_date,
        post_date,
        store_code,
        doc_no,
        Bill_Disc_Perc,
        tender_name,
        RECEIPT_TYPE,
        BT_PRIMARY_PHONE_NO,
        BT_EMAIL,
        MODIFIED_Datetime,
        modified_by,
        notes_lostdoc,
        invn_sbs_item_sid,
        item_type,
        qty,
        orig_price,
        Item_Disc_Perc,
        Price,
        vend_code,
        employee1_SID,
        EMPLOYEE1_LOGIN_NAME,
        dcs_code,
        Customer_Name,
        Cust_Type,
        Valid_From,
        Cust_Birthday,
        First_Sale,
        Last_Sale,
        CUST_ID,
        upc,
        alu,
        description1,
        description2,
        TEXT1,
        attribute,
        item_size,
        Landed_Cost,
        Base_Cost,
        Season,
        vend_name,
        CASHIER_LOGIN_NAME,
        CASE WHEN item_type = 2 THEN qty * -1 ELSE qty END AS Adjusted_Qty,
        ROUND(orig_price) AS Rounded_Orig_Price,
         (Item_Disc_Perc / 100) AS Item_Disc_Rate,
        --ROUND(Item_Disc_Perc / 100, 2) AS Item_Disc_Rate,
        (Bill_Disc_Perc / 100) AS Bill_Disc_Rate,
        --ROUND(Bill_Disc_Perc / 100, 2) AS Bill_Disc_Rate,
        ROUND(Price) AS Rounded_Price
    FROM SalesData
)
SELECT
    TO_CHAR(invc_post_date, 'YYYY') AS YEAR,
    TO_CHAR(invc_post_date, 'MM') AS MONTH,
    TO_CHAR(invc_post_date, 'WW') AS WEEK,
    TO_CHAR(invc_post_date, 'DD') AS DAY,
    TO_CHAR(invc_post_date, 'HH') AS HOUR,
    TRUNC(post_date) AS "Bill Post_date",
    TO_CHAR(invc_post_date, 'HH:MM:SS AM') AS TIME,
    TRUNC(invc_post_date) AS "Bill_date",
    --store_code || doc_no AS "Store_Bill",
    store_code AS "Store_code",
    doc_no AS "Bill",
    TO_CHAR(upc) AS "Item_UPC",
    alu AS "Item_ALU",
    description1 AS "Item_Name",
    description2 AS "Item_Desc2",
    TEXT1 AS "Item_Description",
    attribute AS "Item_Attribute",
    item_size AS "Item_Size",
    Adjusted_Qty AS "Qty",
    Rounded_Orig_Price AS "Orig_price(wT)",
    Item_Disc_Perc AS "Item_Disc%",
    ROUND(Rounded_Orig_Price * Item_Disc_Rate * Adjusted_Qty) AS "Item_DiscAMT(wT)",
    CASE WHEN item_type = 2 THEN Rounded_Price * -1 ELSE Rounded_Price END AS "AfterItem_Disc%_Price(wT)",
    ROUND(Rounded_Price * Adjusted_Qty, 2) AS "AfterItem_Disc%_Price*Qty(wT)",
    Bill_Disc_Perc AS "Bill_Disc%",
    ROUND(Rounded_Price * Bill_Disc_Rate * Adjusted_Qty) AS "Bill_DiscAMT(wT)",
    ROUND((1 - (1 - Item_Disc_Rate) * (1 - Bill_Disc_Rate)) * 100, 2) AS "Total_Disc%",
    ROUND(Rounded_Orig_Price * Item_Disc_Rate * Adjusted_Qty + Rounded_Price * Bill_Disc_Rate * Adjusted_Qty) AS "Total_DiscAMT(wT)",
    ROUND(Rounded_Price * Adjusted_Qty - Rounded_Price * Bill_Disc_Rate * Adjusted_Qty) AS "EXT_Price(wT)",
    CASE COUNT(*) OVER (PARTITION BY doc_no, store_code) WHEN 1 THEN to_char(tender_name) ELSE 'Split' END AS "Payment_Type",
    CASE RECEIPT_TYPE WHEN 0 THEN 'Sale' WHEN 1 THEN 'Return' ELSE 'Deposit' END AS "Receipt_Type",
    Customer_Name,
    BT_PRIMARY_PHONE_NO AS "Cust_Phone",
    Cust_Type AS "Cust Type",
    Valid_From,
    Cust_Birthday,
    BT_EMAIL AS "Cust_Email",
    First_Sale AS "First Sale",
    Last_Sale AS "Last Sale",
    CUST_ID AS "Cust_ID",
    Season,
    REGEXP_SUBSTR(description2, '[^-]+', 1, 3) AS "Category",
    vend_code AS "Vendor_Code",
    vend_name AS "Vendor_name",
    dcs_code AS "DCS_Code",
    employee1_SID AS "Associate ID",
    Upper(EMPLOYEE1_LOGIN_NAME) AS "Associate",
    Upper(CASHIER_LOGIN_NAME) AS "CASHIER",
    ROUND(Landed_Cost) AS "Landed_Cost",
    Base_Cost AS "Base_Cost",
    --ROUND(Base_Cost) AS "Base_Cost",
    TRUNC(MODIFIED_Datetime) AS "Modified_Date",
    modified_by AS "Modified_by",
    notes_lostdoc AS "Bill Note",
    sid
FROM CalculatedData